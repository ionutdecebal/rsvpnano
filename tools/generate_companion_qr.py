"""Generate the static native QR matrix; build-only dependency: qrcode."""
from pathlib import Path
import qrcode

url = 'https://ionutdecebal.github.io/rsvpnano/'
qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=3, border=0)
qr.add_data(url)
qr.make(fit=True)
matrix = qr.get_matrix()
assert len(matrix) == 29
rows = [sum(int(black) << x for x, black in enumerate(row)) for row in matrix]
out = Path(__file__).resolve().parents[1] / 'src/ui/screens/CompanionQr.generated.h'
out.write_text('// Generated by tools/generate_companion_qr.py. QR v3/M; draw with a 4-module quiet zone.\n'
    '#pragma once\n#include <cstdint>\nnamespace screens::companionqr {\n'
    f'inline constexpr char url[] = "{url}";\n'
    'inline constexpr uint8_t modules = 29, quiet = 4, scale = 3;\n'
    'inline constexpr uint32_t rows[] = {\n'
    + ''.join(f'    0x{row:08x}u,\n' for row in rows) + '};\n}\n')
print(out)
