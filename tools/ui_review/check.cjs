// Pass an installed Playwright module path and the generated offline HTML file.
const {chromium}=require(process.argv[2]);
const {pathToFileURL}=require('url');
const fs=require('fs');
const assert=require('assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({acceptDownloads:true,viewport:{width:1440,height:1000}});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(process.argv[3]).href);
 await page.evaluate(()=>localStorage.clear());await page.reload();
 assert(await page.locator('.card').count()>100);
 assert(await page.locator('.card img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth===640)));
 await page.screenshot({path:'/tmp/rsvp-screen-review.png'});
 await page.locator('#search').fill('Dictionary · offline');
 await page.locator('.card').first().click();
 await page.locator('#stage').click({position:{x:200,y:70}});
 await page.locator('#comment').fill('Check the definition contrast <b>literal text</b>');
 await page.locator('#priority').selectOption('blocker');
 await page.locator('#comment-form button[type=submit]').click();
 assert.equal(await page.locator('#comments .comment').count(),1);
 assert.equal(await page.locator('#comments b').count(),0);
 assert.equal(await page.locator('#stage .pin').count(),1);
 await page.getByRole('button',{name:'Mark resolved',exact:true}).click();
 await page.locator('#close').click();
 const exported=page.waitForEvent('download');await page.locator('#export').click();
 const download=await exported;const payload=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 assert.equal(payload.comments[0].status,'resolved');assert(payload.comments[0].point);
 await page.reload();
 await page.getByRole('button',{name:'Feedback',exact:true}).click();
 assert.equal(await page.locator('#content .comment').count(),1);
 await page.evaluate(()=>localStorage.clear());await page.reload();
 const upload={name:'feedback.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(payload))};
 await page.locator('#file').setInputFiles(upload);
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('Imported'));
 await page.locator('#file').setInputFiles(upload);
 await page.getByRole('button',{name:'Feedback',exact:true}).click();
 assert.equal(await page.locator('#content .comment').count(),1);
 await page.locator('#file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"schema":9}')});
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('not a valid'));
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/rsvp-screen-review-mobile.png'});
 assert.deepEqual(errors,[]);
 await browser.close();
 console.log('Offline review: images, pins, safe text, persistence, export/import, deduplication, invalid-file handling and mobile width passed.');
})().catch(e=>{console.error(e);process.exit(1)});
