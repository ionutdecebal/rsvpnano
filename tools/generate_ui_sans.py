"""Generate bounded 4-bit menu glyphs from the repository's OFL Atkinson font.

Run with Python, Pillow, and fontTools. The reader's RFont4 assets are independent.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/atkinson-hyperlegible/AtkinsonHyperlegible-Regular.ttf"
OUTPUT = ROOT / "src/fonts/UiSans.generated.h"


def main():
    cmap = TTFont(SOURCE).getBestCmap()
    points = sorted(set(range(32, 127)) | set(range(160, 384)) | set(range(0x400, 0x460))
                    | {0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2026,
                       0x0218, 0x0219, 0x021a, 0x021b, 0x2039, 0x203a, 0x2190, 0x2191, 0x2192, 0x2193, 0x2197, 0x21b6, 0x232b, 0x2212})
    lines = ["// Generated by tools/generate_ui_sans.py; do not edit.",
             "// Atkinson Hyperlegible: third_party/atkinson-hyperlegible/OFL.txt",
             f"// Source SHA256: {hashlib.sha256(SOURCE.read_bytes()).hexdigest()}",
             '#pragma once', '#include "ui/SansFont.h"', 'namespace ui::sans::assets {']
    total = 0
    for size in (11, 13, 14, 15, 17, 21, 26, 28, 39, 66):
        face = ImageFont.truetype(str(SOURCE), size)
        ascent, descent = face.getmetrics()
        pixels, glyphs = [], []
        for cp in points:
            if size >= 39 and cp not in set(map(ord, " 0123456789:.-?")):
                continue
            vector_arrow = cp in (0x2190, 0x2191, 0x2192, 0x2193, 0x2197, 0x21b6, 0x232b) and cp not in cmap
            if cp not in cmap and not vector_arrow:
                continue
            char = chr(cp)
            left, top, right, bottom = (0, -size + 2, size, 2) if vector_arrow else face.getbbox(char, anchor="ls")
            width, height = right-left, bottom-top
            canvas = Image.new("L", (max(1, width), max(1, height)))
            if vector_arrow:
                # The source face lacks navigation arrows. Code-native strokes
                # keep a single symbol from forcing the whole label to bitmap.
                arrow = ImageDraw.Draw(canvas)
                a, b, m = 2, size - 3, size // 2
                if cp in (0x2191, 0x2193):
                    tip, tail = (a, b) if cp == 0x2191 else (b, a)
                    arrow.line([(m, tail), (m, tip)], fill=255)
                    arrow.line([(a, m), (m, tip), (b, m)], fill=255)
                elif cp == 0x21b6:
                    arrow.line([(b, b), (b, m), (a, m)], fill=255)
                    arrow.line([(m, a), (a, m), (m, b)], fill=255)
                elif cp == 0x232b:
                    arrow.line([(a, m), (m, a), (b, a), (b, b), (m, b), (a, m)], fill=255)
                    arrow.line([(m, m-2), (b-2, m+2)], fill=255)
                    arrow.line([(m, m+2), (b-2, m-2)], fill=255)
                elif cp == 0x2197:
                    arrow.line([(a, b), (b, a), (m, a)], fill=255)
                    arrow.line([(b, a), (b, m)], fill=255)
                else:
                    tip, tail = (a, b) if cp == 0x2190 else (b, a)
                    arrow.line([(tail, m), (tip, m)], fill=255)
                    arrow.line([(m, a), (tip, m), (m, b)], fill=255)
            else:
                ImageDraw.Draw(canvas).text((-left, -top), char, font=face, fill=255, anchor="ls")
            values = [(v+8)//17 for v in canvas.tobytes()] if width*height else []
            offset = len(pixels)
            for i in range(0, len(values), 2):
                pixels.append((values[i] << 4) | (values[i+1] if i+1 < len(values) else 0))
            glyphs.append((cp, offset, width, height, left, top, size if vector_arrow else round(face.getlength(char))))
        lines.append(f"inline constexpr uint8_t pixels{size}[] = {{")
        lines.extend("    "+", ".join(f"0x{v:02x}" for v in pixels[i:i+24])+"," for i in range(0,len(pixels),24))
        lines.append("};")
        lines.append(f"inline constexpr Glyph glyphs{size}[] = {{")
        lines.extend("    {"+", ".join(str(v) for v in glyph)+"}," for glyph in glyphs)
        lines.append("};")
        lines.append(f"inline constexpr Font font{size}{{glyphs{size}, pixels{size}, {len(glyphs)}, {size}, {ascent}, {ascent+descent}}};")
        total += len(pixels)+len(glyphs)*16
    lines.append("}")
    OUTPUT.write_text("\n".join(lines)+"\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)}; approximately {total:,} bytes of flash glyph data")


if __name__ == "__main__":
    main()
