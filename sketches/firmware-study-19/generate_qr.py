"""Generate the static companion QR. Build-only dependencies: qrcode, Pillow, zxing-cpp."""
import json
from pathlib import Path
import qrcode
import zxingcpp

URL = 'https://ionutdecebal.github.io/rsvpnano/'
qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=3, border=4)
qr.add_data(URL)
qr.make(fit=True)
matrix = qr.get_matrix()
size = len(matrix)
assert size * 3 <= 112, 'QR must fit the 128px content area with integer-size modules.'
result = zxingcpp.read_barcode(qr.make_image().convert('RGB'))
assert result and result.text == URL
pixels = ' '.join(f'M{x} {y}h1v1h-1z' for y,row in enumerate(matrix) for x,black in enumerate(row) if black)
svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{size*3}" height="{size*3}" viewBox="0 0 {size} {size}" shape-rendering="crispEdges" aria-hidden="true"><rect width="{size}" height="{size}" fill="#fff"/><path d="{pixels}" fill="#000"/></svg>'
root = Path(__file__).resolve().parent
(root / 'companion-qr.svg').write_text(svg + '\n')
(root / 'companion-qr.js').write_text('// Generated by generate_qr.py; no runtime QR library or network request.\nconst companionQrSvg=' + json.dumps(svg) + ';\nconst companionUrl=' + json.dumps(URL) + ';\n')
print(f'Verified QR: {size*3} × {size*3}px, version {qr.version}, M correction, four-module quiet zone: {URL}')
